#!/usr/bin/env node
// Generate src/floor/generated.rs: the Bundu floor, read from the Mzizi token source
// (mzizi-registry styles/pattern/tokens.css) and never typed here ("everything uses tokens").
//
//   node scripts/generate-floor-tokens.mjs --from tokens.css --sha <registry commit>        write
//   node scripts/generate-floor-tokens.mjs --from tokens.css --sha <registry commit> --check compare
//
// Which token is which layer and kind is structure and lives in MANIFEST below; every pixel
// value and ratio comes from the CSS. Desktop values are the overrides in the
// `(pointer: fine)` media block.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "../src/floor/generated.rs");
const arg = (n) => {
  const i = process.argv.indexOf(n);
  return i === -1 ? undefined : process.argv[i + 1];
};
const from = arg("--from");
const sha = arg("--sha");
if (!from || !sha) {
  console.error("usage: --from <tokens.css> --sha <registry commit> [--check]");
  process.exit(2);
}

const css = readFileSync(from, "utf8");
const MEDIA = /@media \(min-width: 64rem\) and \(pointer: fine\)[^{]*\{\s*:root \{([^}]*)\}\s*\}/;
const desktopBlock = MEDIA.exec(css)?.[1] ?? "";
const base = css.replace(MEDIA, "");
const decls = (text) => {
  const m = new Map();
  for (const d of text.matchAll(/(--[a-z0-9-]+):\s*([^;]+);/g)) m.set(d[1], d[2].trim());
  return m;
};
const baseVars = decls(base);
const desktopVars = decls(desktopBlock);
const px = (v, name) => {
  const m = /^(-?[0-9.]+)(rem|px)$/.exec(v ?? "");
  if (!m) throw new Error(`${name} is not a rem or px length: ${v}`);
  return m[2] === "rem" ? Number(m[1]) * 16 : Number(m[1]);
};
const get = (name, vars = baseVars) => {
  if (!vars.has(name)) throw new Error(`${name} is not in the token source`);
  return vars.get(name);
};

// token, layer, kind. Structure only.
const MANIFEST = [
  ["--space-page-x", "Layout", "Padding"],
  ["--space-page-x-wide", "Layout", "Padding"],
  ["--space-section", "Layout", "Gap"],
  ["--space-container", "Containers", "Padding"],
  ["--space-container-gap", "Containers", "Gap"],
  ["--space-card", "Cards", "Padding"],
  ["--space-card-gap", "Cards", "Gap"],
  ["--space-card-stack", "Cards", "Gap"],
  ["--space-control-x", "Controls", "Padding"],
  ["--space-field-x", "Controls", "Padding"],
  ["--space-control-gap", "Controls", "Gap"],
  ["--space-control-between", "Controls", "Gap"],
  ["--space-label-gap", "Controls", "Gap"],
  ["--space-chip-x", "Chips", "Padding"],
  ["--space-pill-x", "Pills", "Padding"],
  ["--space-pill-gap", "Pills", "Gap"],
];
const num = (n) => (Number.isInteger(n) ? `${n}.0` : String(n));
const rows = MANIFEST.map(([token, layer, kind]) => {
  const d = px(get(token), token);
  const dense = baseVars.has(`${token}-dense`) ? px(get(`${token}-dense`), token) : d;
  return `    t("${token}", Layer::${layer}, Kind::${kind}, ${num(d)}, ${num(dense)}),`;
});
const raw = `// GENERATED by scripts/generate-floor-tokens.mjs from mzizi-registry styles/pattern/tokens.css
// at ${sha}. Do not edit: change the token source and regenerate.
use super::tokens::{Kind, Layer, SpacingToken, t};

/// The registry commit the floor was read from.
#[allow(dead_code)]
pub const SOURCE_SHA: &str = "${sha}";

/// Every per-layer spacing token (\`--space-*\`), default and dense, in pixels.
pub const SPACING_LAYERS: [SpacingToken; ${MANIFEST.length}] = [
${rows.join("\n")}
];

/// Body line height (\`--leading-floor\`).
pub const LEADING_BODY: f64 = ${get("--leading-floor")};
/// Unplaced padding floor (\`--inset-floor\`).
pub const UNPLACED_PADDING_PX: f64 = ${num(px(get("--inset-floor"), "--inset-floor"))};
/// Unplaced gap floor (\`--gap-floor\`).
pub const UNPLACED_GAP_PX: f64 = ${num(px(get("--gap-floor"), "--gap-floor"))};
/// Hit region on touch (\`--target-floor\`).
pub const HIT_TOUCH_PX: f64 = ${num(px(get("--target-floor"), "--target-floor"))};
/// Hit region at desktop density (\`--target-floor\` in the fine-pointer block).
pub const HIT_DESKTOP_PX: f64 = ${num(px(get("--target-floor", desktopVars), "--target-floor"))};
/// The drawn minimum of a control at desktop density (\`--control-floor\` in the fine-pointer block).
pub const CONTROL_DRAWN_FLOOR_PX: f64 = ${num(px(get("--control-floor", desktopVars), "--control-floor"))};
`;
const body = execFileSync("rustfmt", ["--edition", "2024", "--emit", "stdout"], {
  input: raw,
  encoding: "utf8",
}).replace(/^\s*\n?Fixed[^\n]*\n/, "");
if (process.argv.includes("--check")) {
  if (readFileSync(OUT, "utf8") !== body) {
    console.error("src/floor/generated.rs is out of date with the token source");
    process.exit(1);
  }
  console.log("floor tokens match the token source at " + sha);
} else {
  writeFileSync(OUT, body);
  console.log("wrote src/floor/generated.rs at " + sha);
}
