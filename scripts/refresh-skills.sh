#!/usr/bin/env bash
# Refresh the vendored copy of the agent skills the fundi agent embeds.
#
# The TypeScript CLI read the skills from its npm dependency, @nyuchi/mzizi-skills. A
# Rust binary has no node_modules, so it embeds a snapshot instead: skills/index.json
# plus one skills/<name>/SKILL.md per entry, and src/fundi/skills_data.rs, which
# `include_str!`s each file (generated here, committed, never edited by hand).
#
# Usage: scripts/refresh-skills.sh [path-to-mzizi-skills]   (default: ./node_modules/@nyuchi/mzizi-skills,
#        else a checkout of mzizi-dev/agent-tools/mzizi-skills)
set -euo pipefail
src="${1:-}"
root="$(cd "$(dirname "$0")/.." && pwd)"
if [ -z "$src" ]; then
  for c in "$root/node_modules/@nyuchi/mzizi-skills" "$root/../agent-tools/mzizi-skills"; do
    [ -f "$c/index.json" ] && src="$c" && break
  done
fi
[ -f "$src/index.json" ] || { echo "no mzizi-skills package found; pass its path" >&2; exit 1; }
rm -rf "$root/skills"
mkdir -p "$root/skills"
python3 - "$src" "$root" <<'PY'
import json, os, shutil, sys
src, root = sys.argv[1], sys.argv[2]
index = json.load(open(os.path.join(src, "index.json")))
keep = {"version": index.get("version"), "skills": []}
rows = []
for s in index["skills"]:
    f = s.get("file")
    if not f:
        continue
    dst = os.path.join(root, "skills", s["name"], "SKILL.md")
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copyfile(os.path.join(src, f), dst)
    keep["skills"].append({"name": s["name"], "file": f"{s['name']}/SKILL.md"})
    rows.append(s["name"])
json.dump(keep, open(os.path.join(root, "skills", "index.json"), "w"), indent=2)
open(os.path.join(root, "skills", "index.json"), "a").write("\n")
out = ["//! GENERATED by scripts/refresh-skills.sh from @nyuchi/mzizi-skills %s. Do not edit.\n" % index.get("version"),
       "/// The embedded skills, in the package's index order: (name, SKILL.md).\n",
       "pub const EMBEDDED: &[(&str, &str)] = &[\n"]
for n in rows:
    out.append('    ("%s", include_str!("../../skills/%s/SKILL.md")),\n' % (n, n))
out.append("];\n")
open(os.path.join(root, "src", "fundi", "skills_data.rs"), "w").write("".join(out))
PY
echo "vendored $(ls "$root/skills" | grep -vc index.json) skills from $src"
